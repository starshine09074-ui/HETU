#!/usr/bin/env python3
"""Exercise a complete Hetu requirement-to-release flow against a disposable database.

Usage: python3 scripts/e2e_workflow.py [base-url]
The script creates test data and should only be run against a disposable instance.
"""
import json
import sys
import urllib.error
import urllib.request
from datetime import date

BASE = (sys.argv[1] if len(sys.argv) > 1 else "http://127.0.0.1:8093").rstrip("/")
TOKENS = {}
checks = 0


def request(method, path, user=None, body=None, expect=True):
    global checks
    headers = {"Content-Type": "application/json"}
    if user:
        headers["Authorization"] = "Bearer " + TOKENS[user]
    data = None if body is None else json.dumps(body).encode()
    req = urllib.request.Request(BASE + path, data=data, headers=headers, method=method)
    try:
        with urllib.request.urlopen(req, timeout=15) as response:
            status, payload = response.status, response.read()
    except urllib.error.HTTPError as error:
        status, payload = error.code, error.read()
    parsed = json.loads(payload) if payload else {}
    successful = status < 400 and parsed.get("code", 200) == 200
    checks += 1
    if expect and not successful:
        raise AssertionError(f"{method} {path}: expected success, got HTTP {status}: {parsed}")
    if not expect and successful:
        raise AssertionError(f"{method} {path}: expected denial/failure, got {parsed}")
    return parsed


def data(method, path, user, body=None):
    return request(method, path, user, body).get("data")


def login(user, password="admin123"):
    result = request("POST", "/login", body={"username": user, "password": password})
    TOKENS[user] = result["token"]
    request("GET", "/getInfo", user)


def state(user, kind, ident, value, note="E2E workflow validation"):
    return request("PATCH", f"/hetu/{kind}/{ident}/status", user,
                   {"status": value, "note": note})


def create_closed_bug(user, title, task_id, assignee, cause, severity):
    bug = data("POST", "/hetu/bugs", user, {
        "title": title, "taskId": task_id, "assignee": assignee,
        "rootCause": cause, "severity": severity, "type": "FUNCTIONAL",
        "description": "Generated by full-flow integration test", "steps": "E2E"})
    bug_id = bug["id"]
    state("tester", "bugs", bug_id, "IN_PROGRESS")
    state(assignee_user[assignee], "bugs", bug_id, "VERIFYING")
    state("tester", "bugs", bug_id, "CLOSED")
    return bug_id


assignee_user = {"前端开发": "frontend", "后端开发": "backend"}

for account in ("pm", "director", "frontend", "backend", "tester", "ops"):
    login(account)

# RuoYi account/password administration APIs remain available to administrators.
login("admin")
request("GET", "/system/role/list?pageNum=1&pageSize=20", "admin")
request("POST", "/system/user", "admin", {
    "deptId": 103, "userName": "e2e-managed", "nickName": "E2E 管理账号",
    "password": "admin123", "status": "0", "sex": "0", "roleIds": [12], "postIds": []})
managed = request("GET", "/system/user/list?userName=e2e-managed&pageNum=1&pageSize=10", "admin")
managed_user_id = managed["rows"][0]["userId"]
request("PUT", "/system/user/resetPwd", "admin", {
    "userId": managed_user_id, "password": "Hetu-test-2026"})
login("e2e-managed", "Hetu-test-2026")

# Role boundaries: PM plans requirements, directors assign tasks, ops publishes.
request("POST", "/hetu/tasks", "pm", {"title": "must be forbidden"}, expect=False)
request("POST", "/hetu/releases", "director", {"name": "must be forbidden", "projectId": 1}, expect=False)
request("POST", "/hetu/releases/1/publish", "frontend", expect=False)

# PM creates and approves a requirement in the existing demo project.
requirement = data("POST", "/hetu/requirements", "pm", {
    "projectId": 1, "title": "认证功能优化", "owner": "产品经理", "version": "v1.1",
    "content": "晋康管家支持为未通过人脸识别的儿童提交身份证、户口本、出生证明和已实名监护人身份证，经人工审核后自动绑定家人。"})
req_id = requirement["id"]
state("pm", "requirements", req_id, "IN_PROGRESS")
state("pm", "requirements", req_id, "APPROVED")

# Director decomposes the approved request for two developers.
tasks = {}
for title, user, assignee in (("认证优化前端", "frontend", "前端开发"), ("认证优化后端", "backend", "后端开发")):
    row = data("POST", "/hetu/tasks", "director", {
        "projectId": 1, "requirementId": req_id, "title": title,
        "description": "实现并交付认证功能优化", "assignee": assignee,
        "estimateHours": 10, "priority": "HIGH", "status": "TODO"})
    tasks[user] = row["id"]

# Both developers record work and submit. Frontend fails the first test, fixes,
# and passes on retest; backend passes the first test.
for user, task_id in tasks.items():
    state(user, "tasks", task_id, "IN_PROGRESS")
    data("POST", "/hetu/worklog", user, {"taskId": task_id, "hours": 2,
        "workDate": str(date.today()), "note": "实现并提交测试"})
    request("PATCH", f"/hetu/tasks/{task_id}/progress", user, {"progress": 100, "note": "首次提测"})
    request("POST", f"/hetu/tasks/{task_id}/accept-testing", "tester")
    if user == "frontend":
        state("tester", "tasks", task_id, "IN_PROGRESS", "测试不通过，缺陷修复后复测")
        data("POST", "/hetu/worklog", user, {"taskId": task_id, "hours": 1,
            "workDate": str(date.today()), "note": "修复后重新提测"})
        request("PATCH", f"/hetu/tasks/{task_id}/progress", user, {"progress": 100, "note": "修复完成，重新提测"})
    state("tester", "tasks", task_id, "DONE", "测试通过")

# Cover all development-bug severity ratios against a 10h task, including the
# original critical example (50% = 5h), and fixed/no-deduction classifications.
for severity, expected in (("CRITICAL", "-5.00"), ("HIGH", "-3.00"),
                           ("MEDIUM", "-1.00"), ("LOW", "-0.50")):
    developer = "backend" if severity == "HIGH" else "frontend"
    assignee = "后端开发" if developer == "backend" else "前端开发"
    create_closed_bug("tester", f"开发缺陷扣分-{severity}", tasks[developer], assignee, "PRODUCT_DEFECT", severity)

for cause in ("REQUIREMENT_CHANGE", "ENVIRONMENT"):
    for severity, expected in (("CRITICAL", "-5.00"), ("HIGH", "-3.00"),
                               ("MEDIUM", "-1.00"), ("LOW", "0.00")):
        create_closed_bug("tester", f"固定扣分-{cause}-{severity}", tasks["backend"], "后端开发", cause, severity)

for cause in ("NO_DEDUCTION", "DUPLICATE", "NOT_REPRODUCIBLE"):
    create_closed_bug("tester", f"不扣分-{cause}", tasks["frontend"], "前端开发", cause, "CRITICAL")

bug_rows = data("GET", "/hetu/bugs", "tester")
expected_scores = {
    "开发缺陷扣分-CRITICAL": "-5.00", "开发缺陷扣分-HIGH": "-3.00",
    "开发缺陷扣分-MEDIUM": "-1.00", "开发缺陷扣分-LOW": "-0.50",
}
for cause in ("REQUIREMENT_CHANGE", "ENVIRONMENT"):
    expected_scores.update({f"固定扣分-{cause}-CRITICAL": "-5.00",
                            f"固定扣分-{cause}-HIGH": "-3.00",
                            f"固定扣分-{cause}-MEDIUM": "-1.00",
                            f"固定扣分-{cause}-LOW": "0.00"})
for cause in ("NO_DEDUCTION", "DUPLICATE", "NOT_REPRODUCIBLE"):
    expected_scores[f"不扣分-{cause}"] = "0.00"
by_title = {row["title"]: f'{float(row["scoreHours"]):.2f}' for row in bug_rows}
for title, expected in expected_scores.items():
    actual = by_title.get(title)
    checks += 1
    if actual != expected:
        raise AssertionError(f"deduction mismatch for {title}: expected {expected}, got {actual}")

task_rows = data("GET", "/hetu/tasks", "tester")
for task_id in tasks.values():
    checks += 1
    if next(row for row in task_rows if row["id"] == task_id)["status"] != "DONE":
        raise AssertionError(f"task {task_id} should be DONE after passing tests")

# Release 1: tester passes, ops publishes, PM requests improvement and logs an
# online LOW development bug. The same PM must verify the follow-up release.
release1 = data("POST", "/hetu/releases", "ops", {
    "projectId": 1, "name": "认证优化-首发", "description": "认证需求与首轮修复",
    "releaseDate": str(date.today())})
r1 = release1["id"]
data("POST", f"/hetu/releases/{r1}/items", "ops", {"entityType": "requirement", "entityId": req_id})
request("POST", f"/hetu/releases/{r1}/submit-test", "tester")
request("POST", f"/hetu/releases/{r1}/publish", "tester", expect=False)
request("POST", f"/hetu/releases/{r1}/publish", "ops")
request("POST", f"/hetu/releases/{r1}/verify", "ops", {"status": "VERIFIED"}, expect=False)
request("POST", f"/hetu/releases/{r1}/verify", "pm", {"status": "NEEDS_IMPROVEMENT", "note": "线上轻微问题，待完善"})

online_bug = data("POST", "/hetu/bugs", "pm", {
    "title": "线上轻微问题-儿童认证提示", "taskId": tasks["frontend"], "assignee": "前端开发",
    "rootCause": "PRODUCT_DEFECT", "severity": "LOW", "type": "FUNCTIONAL"})
online_id = online_bug["id"]
state("tester", "bugs", online_id, "IN_PROGRESS")
state("frontend", "bugs", online_id, "VERIFYING", "线上问题修复完成")
state("tester", "bugs", online_id, "CLOSED", "复测通过")
bug_rows = data("GET", "/hetu/bugs", "tester")
online = next(row for row in bug_rows if row["id"] == online_id)
checks += 1
if f'{float(online["scoreHours"]):.2f}' != "-0.50":
    raise AssertionError(f"online LOW development bug should deduct 0.50 hours, got {online['scoreHours']}")
deductions = data("GET", f"/hetu/deductions?from={date.today()}&to={date.today()}", "tester")
bug_deductions = [row for row in deductions if row["sourceType"] == "BUG"]
checks += 1
if len(bug_deductions) != 16:
    raise AssertionError(f"expected 16 bug deduction records including zero-score cases, got {len(bug_deductions)}")
checks += 1
if f'{sum(float(row["hours"]) for row in bug_deductions):.2f}' != "-28.00":
    raise AssertionError("bug deduction ledger total should be -28.00 hours")

# Release 2: test, publish, original product manager verifies; both plans close.
release2 = data("POST", "/hetu/releases", "ops", {
    "projectId": 1, "name": "认证优化-修复版", "description": "线上问题修复",
    "releaseDate": str(date.today())})
r2 = release2["id"]
data("POST", f"/hetu/releases/{r2}/items", "ops", {"entityType": "bug", "entityId": online_id})
request("POST", f"/hetu/releases/{r2}/submit-test", "tester")
request("POST", f"/hetu/releases/{r2}/publish", "ops")
request("POST", f"/hetu/releases/{r2}/verify", "pm", {"status": "VERIFIED", "note": "原需求提出人验收通过"})
for release_id in (r1, r2):
    request("POST", f"/hetu/releases/{release_id}/close", "ops", {"note": "E2E 手动关闭"})

release_rows = data("GET", "/hetu/releases?projectId=1", "pm")
for release_id in (r1, r2):
    current = next(row for row in release_rows if row["id"] == release_id)
    checks += 1
    if current["status"] != "CLOSED":
        raise AssertionError(f"release {release_id} should be CLOSED, got {current['status']}")

print(f"PASS: {checks} assertions; requirement -> tasks -> progress/worklogs -> failed and passed testing -> scoring/no-scoring defects -> two releases -> PM verification -> manual close")
